def install(bot, db):
    global _DB
    _DB = db
    for name, wrapper in {
        "send_message": _send_message, "reply_to": _reply_to,
        "edit_message_text": _edit_message_text, "send_photo": _send_caption,
        "send_document": _send_caption, "send_video": _send_caption,
        "send_audio": _send_caption, "send_media_group": _send_media_group,
        "answer_callback_query": _answer_callback,
    }.items():
        original = getattr(bot, name, None)
        if original and not getattr(original, "_hmax_i18n", False):
            wrapped = wrapper(original)
            wrapped._hmax_i18n = True
            setattr(bot, name, wrapped)


def get_language(user_id, default="ar"):
    key = str(user_id)
    if key in _CACHE:
        return _CACHE[key]
    try:
        if _DB:
            snap = _DB.collection("users").document(key).get()
            lang = (snap.to_dict() or {}).get("lang") if snap.exists else None
            if lang in SUPPORTED_LANGUAGES:
                _CACHE[key] = lang
                return lang
    except Exception:
        pass
    return default


def normalize_reply_button(user_id, text):
    """Map translated reply-keyboard labels to the handler's canonical labels."""
    if not isinstance(text, str):
        return text
    return _REPLY_BUTTONS.get(get_language(user_id), {}).get(text, text)


def has_language(user_id):
    if str(user_id) in _CACHE:
        return _CACHE[str(user_id)] in SUPPORTED_LANGUAGES
    try:
        if _DB:
            snap = _DB.collection("users").document(str(user_id)).get()
            lang = (snap.to_dict() or {}).get("lang") if snap.exists else None
            if lang in SUPPORTED_LANGUAGES:
                _CACHE[str(user_id)] = lang
                return True
    except Exception:
        pass
    return False


def set_language(user_id, language):
    language = str(language).lower().split("-")[0]
    if language not in SUPPORTED_LANGUAGES:
        return False
    _CACHE[str(user_id)] = language
    try:
        if not _DB:
            return False
        _DB.collection("users").document(str(user_id)).set({"lang": language}, merge=True)
        return True
    except Exception:
        return False


def bind_callback(callback_id, user_id):
    _CALLBACK_USERS[str(callback_id)] = str(user_id)


def translate_text(text, language):
    if not isinstance(text, str) or language == "ar":
        return text
    phrases = _TEXT.get(language, {})
    for source in sorted(phrases, key=len, reverse=True):
        text = text.replace(source, phrases[source])
    return text


def translate_product_description(product_id, text, language):
    """Use a complete catalog translation when one is available."""
    if not isinstance(text, str) or language == "ar":
        return text
    localized = _PRODUCT_DESCRIPTIONS.get(str(product_id), {}).get(language)
    return localized if localized else translate_text(text, language)


def translate_static_content(content_id, text, language):
    """Translate a fixed long-form tool or firmware description by its key."""
    if not isinstance(text, str) or language == "ar":
        return text
    localized = _STATIC_CONTENT.get(str(content_id), {}).get(language)
    return localized if localized else translate_text(text, language)


def translate_button(text, language):
    if not isinstance(text, str) or language == "ar":
        return text
    table = dict(_TEXT.get(language, {}))
    table.update(_BUTTONS.get(language, {}))
    if text in table:
        return table[text]
    phrases = _BUTTON_PHRASES.get(language, {})
    if text in phrases:
        return phrases[text]
    # Back labels vary by destination throughout the large catalog. The
    # callback_data remains unchanged, so a short localized label is safe.
    if text.startswith(("🔙 رجوع", "🔙 العودة", "🏠 رجوع")):
        return "🔙 Back" if language == "en" else "🔙 Retour"
    return text


def _markup(markup, language):
    table = dict(_TEXT.get(language, {}))
    table.update(_BUTTONS.get(language, {}))
    for row in getattr(markup, "keyboard", []) or []:
        for button in row:
            if getattr(button, "text", None) in table:
                button.text = table[button.text]
            elif isinstance(getattr(button, "text", None), str):
                button.text = translate_button(button.text, language)
    return markup


def _lang(user_id):
    return get_language(user_id)


def _send_message(original):
    def call(*args, **kwargs):
        uid = kwargs.get("chat_id", args[0] if args else None)
        lang = _lang(uid)
        text = kwargs.get("text", args[1] if len(args) > 1 else None)
        if isinstance(text, str):
            if len(args) > 1:
                args = (args[0], translate_text(text, lang), *args[2:])
            else:
                kwargs["text"] = translate_text(text, lang)
        if "reply_markup" in kwargs:
            kwargs["reply_markup"] = _markup(kwargs["reply_markup"], lang)
        return original(*args, **kwargs)
    return call


def _reply_to(original):
    def call(message, text, *args, **kwargs):
        lang = _lang(message.chat.id)
        text = translate_text(text, lang)
        if "reply_markup" in kwargs:
            kwargs["reply_markup"] = _markup(kwargs["reply_markup"], lang)
        return original(message, text, *args, **kwargs)
    return call


def _edit_message_text(original):
    def call(*args, **kwargs):
        uid = kwargs.get("chat_id", args[1] if len(args) > 1 else None)
        lang = _lang(uid)
        text = kwargs.get("text", args[0] if args else None)
        if isinstance(text, str):
            if args:
                args = (translate_text(text, lang), *args[1:])
            else:
                kwargs["text"] = translate_text(text, lang)
        if "reply_markup" in kwargs:
            kwargs["reply_markup"] = _markup(kwargs["reply_markup"], lang)
        return original(*args, **kwargs)
    return call


def _send_caption(original):
    def call(*args, **kwargs):
        uid = kwargs.get("chat_id", args[0] if args else None)
        lang = _lang(uid)
        if len(args) > 2 and isinstance(args[2], str):
            args = (*args[:2], translate_text(args[2], lang), *args[3:])
        elif isinstance(kwargs.get("caption"), str):
            kwargs["caption"] = translate_text(kwargs["caption"], lang)
        if "reply_markup" in kwargs:
            kwargs["reply_markup"] = _markup(kwargs["reply_markup"], lang)
        return original(*args, **kwargs)
    return call


def _answer_callback(original):
    def call(callback_id, *args, **kwargs):
        uid = _CALLBACK_USERS.pop(str(callback_id), None)
        if uid is not None:
            lang = _lang(uid)
            if args and isinstance(args[0], str):
                args = (translate_text(args[0], lang), *args[1:])
            elif isinstance(kwargs.get("text"), str):
                kwargs["text"] = translate_text(kwargs["text"], lang)
        return original(callback_id, *args, **kwargs)
    return call


def _send_media_group(original):
    def call(*args, **kwargs):
        uid = kwargs.get("chat_id", args[0] if args else None)
        lang = _lang(uid)
        media = kwargs.get("media", args[1] if len(args) > 1 else [])
        for item in media or []:
            if isinstance(getattr(item, "caption", None), str):
                item.caption = translate_text(item.caption, lang)
        return original(*args, **kwargs)
    return call
